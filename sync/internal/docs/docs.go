// Package docs renders the model as Markdown: a README per package, written
// beside its v1/ directory, and an index of every package.
//
// Like the .proto files, every README is generated (CLAUDE.md rule 2), and
// from the same model rather than from the emitted text.
package docs

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/shokki-engineering/protobuf-ota/sync/internal/model"
	"github.com/shokki-engineering/protobuf-ota/sync/internal/spec"
)

// Generator renders one model.
type Generator struct {
	M   *model.Model
	Pin *spec.Pin
}

// New returns a Generator for m, stamping pin's revisions into every page.
func New(m *model.Model, pin *spec.Pin) *Generator { return &Generator{M: m, Pin: pin} }

// Generate writes every package README and the index under out, returning
// how many files it wrote.
func (g *Generator) Generate(out string) (int, error) {
	n := 0
	for _, p := range g.M.Packages {
		dir := filepath.Join(append([]string{out}, p.Segments()...)...)
		if err := write(dir, g.page(p)); err != nil {
			return n, err
		}
		n++
	}
	if err := write(filepath.Join(out, "opentravel"), g.index()); err != nil {
		return n, err
	}
	return n + 1, nil
}

func write(dir, body string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "README.md"), []byte(body), 0o644)
}

// banner is the notice every page opens with.
func (g *Generator) banner() string {
	return fmt.Sprintf("> [!IMPORTANT]\n> Generated by `just docs` from the OpenTravel %s XML message suite and\n"+
		"> code list %s, OpenTravel-Specifications revision %s (`%s`).\n> Do not edit by hand.\n",
		g.Pin.SuiteLabel, g.Pin.CodeListLabel, g.Pin.Version, g.Pin.Short())
}

// badge renders a shields.io badge. Shields reads "-" and "_" as separators,
// so both are doubled in the text.
func badge(label, message, color, link string) string {
	esc := strings.NewReplacer("-", "--", "_", "__", " ", "%20")
	return fmt.Sprintf("[![%s](https://img.shields.io/badge/%s-%s-%s)](%s)",
		label, esc.Replace(label), esc.Replace(message), color, link)
}

// cell makes text safe inside a Markdown table cell: one line, no pipes.
func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

// firstSentence is a doc comment's opening sentence, for a table.
func firstSentence(doc string) string {
	doc = strings.Join(strings.Fields(strings.SplitN(doc, "\n\n", 2)[0]), " ")
	if i := strings.Index(doc, ". "); i > 0 {
		doc = doc[:i+1]
	}
	if len(doc) > 160 {
		doc = doc[:157] + "..."
	}
	return doc
}

// relLink is the path from the index to a package's README.
func relLink(p *model.Package) string {
	return strings.Join(p.Segments()[1:], "/") + "/README.md"
}
