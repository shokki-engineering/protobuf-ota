// Package emit writes the planned packages as .proto text.
//
// One top-level declaration per file -- a message with what is nested in
// it, or an enum -- plus messages.proto for a package's requests and
// responses and service.proto for its methods (CLAUDE.md rule 2). The text
// is close to what `buf format` produces, and `just sync` runs buf format
// over it, so the committed tree is exactly buf's.
package emit

import (
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/shokki-engineering/protobuf-ota/sync/internal/model"
	"github.com/shokki-engineering/protobuf-ota/sync/internal/naming"
	"github.com/shokki-engineering/protobuf-ota/sync/internal/plan"
	"github.com/shokki-engineering/protobuf-ota/sync/internal/spec"
)

// Emitter writes one model.
type Emitter struct {
	M   *model.Model
	Pin *spec.Pin
}

// New returns an Emitter for m, stamping pin into every banner.
func New(m *model.Model, pin *spec.Pin) *Emitter { return &Emitter{M: m, Pin: pin} }

// javaPrefix is prepended to the proto package for java_package.
const javaPrefix = "io.github.shokkiengineering."

// Generate writes every package under out/opentravel, replacing what is
// there. The tree is rewritten, not merged into: a type that stops being
// generated would otherwise leave a file behind that still compiles and
// still lints, and nothing would report it.
func (e *Emitter) Generate(out string) (int, error) {
	root := filepath.Join(out, "opentravel")
	if err := os.RemoveAll(root); err != nil {
		return 0, err
	}
	n, err := e.vocab(out)
	if err != nil {
		return 0, err
	}
	for _, p := range e.M.Packages {
		k, err := e.pkg(p, out)
		if err != nil {
			return 0, err
		}
		n += k
	}
	return n, nil
}

// pkg writes one package.
func (e *Emitter) pkg(p *model.Package, out string) (int, error) {
	dir := filepath.Join(append([]string{out}, append(p.Segments(), "v1")...)...)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, err
	}
	files := map[string]string{}
	byFile := map[string][]*plan.Message{}
	var order []string
	for _, m := range p.Plan.Messages {
		if len(byFile[m.File]) == 0 {
			order = append(order, m.File)
		}
		byFile[m.File] = append(byFile[m.File], m)
	}
	for _, f := range order {
		files[f] = e.messageFile(p, f, byFile[f])
	}
	for _, en := range p.Plan.Enums {
		files[en.File] = e.enumFile(p, en)
	}
	files["messages.proto"] = e.requests(p)
	files["service.proto"] = e.service(p)
	for file, body := range files {
		full := filepath.Join(dir, filepath.FromSlash(file))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return 0, err
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			return 0, err
		}
	}
	return len(files), nil
}

// subPackage is the proto package of a file under v1/: the package itself,
// or its types, codes or enums subpackage.
func subPackage(p *model.Package, file string) string {
	if sub := plan.SubOf(file); sub != "" {
		return p.Proto() + "." + sub
	}
	return p.Proto()
}

// header writes the banner, package, imports and file options. base may
// carry its subpackage directory; the outer class is named for the file.
func (e *Emitter) header(w *writer, protoPkg, base string, imports map[string]bool) {
	base = base[strings.LastIndex(base, "/")+1:]
	w.line(0, "// Copyright 2026 Shokki Engineering.")
	w.line(0, "// SPDX-License-Identifier: Apache-2.0")
	w.line(0, "//")
	w.line(0, "// Generated by sync from the OpenTravel %s XML message suite and", e.Pin.SuiteLabel)
	w.line(0, "// code list %s, read from OpenTravel-Specifications at", e.Pin.CodeListLabel)
	w.line(0, "// revision %s (%s).", e.Pin.Version, e.Pin.Short())
	w.line(0, "// DO NOT EDIT.")
	w.line(0, "//")
	w.line(0, "// Regenerate with: just sync")
	w.line(0, "// Revision history: docs/spec.md")
	w.line(0, "")
	w.line(0, `syntax = "proto3";`)
	w.line(0, "")
	w.line(0, "package %s;", protoPkg)
	w.line(0, "")
	var list []string
	for imp := range imports {
		list = append(list, imp)
	}
	sort.Strings(list)
	for _, imp := range list {
		w.line(0, "import %s;", quote(imp))
	}
	if len(list) > 0 {
		w.line(0, "")
	}
	w.line(0, "option java_multiple_files = true;")
	w.line(0, "option java_outer_classname = %s;", quote(naming.Pascal(strings.TrimSuffix(base, ".proto"))+"Proto"))
	w.line(0, "option java_package = %s;", quote(javaPrefix+protoPkg))
	w.line(0, "")
}

// local resolves a file of package p to its import path.
func local(p *model.Package, base string) string {
	return strings.Join(append(append([]string{"protobuf"}, p.Segments()...), "v1", base), "/")
}

// importFor is the import a field type needs, or "" for a scalar.
func importFor(p *model.Package, file string) string {
	switch {
	case file == "":
		return ""
	case strings.HasPrefix(file, "google/"), strings.HasPrefix(file, "buf/"):
		return file // a well-known or dependency import
	default:
		return local(p, file)
	}
}
